"""UW-D dense underwater depth dataset.

The dataset is expected to have the following layout::

    root/
      uw/<scene>/<water_type>/uw_<frame>.png
      depth/<scene>/depth_<frame>.hdf5

Manifest files are generated by ``tools/build_uwd_manifests.py``.  Paths in a
manifest are relative to the dataset root so that the same files work on the
workstation and the training server.
"""

from __future__ import annotations

import json
import random
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

import h5py
import numpy as np
import torch
import torch.nn.functional as F
from PIL import Image
from torch.utils.data import Dataset


WATER_TYPES = (
    "Type-1",
    "Type-3",
    "Type-5",
    "Type-7",
    "Type-9",
    "Type-IB",
    "Type-II",
    "Type-III",
)
WATER_TYPE_TO_LABEL = {name: index for index, name in enumerate(WATER_TYPES)}


def _parse_size(size: int | Sequence[int]) -> Tuple[int, int]:
    if isinstance(size, int):
        return size, size
    if len(size) != 2:
        raise ValueError("size must be an int or a (height, width) pair")
    return int(size[0]), int(size[1])


def _resize_dense_pair(
    image: torch.Tensor,
    depth: torch.Tensor,
    valid_mask: torch.Tensor,
    output_size: Tuple[int, int],
) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """Resize an RGB/depth pair while preventing invalid depth from bleeding."""

    image = F.interpolate(
        image[None], output_size, mode="bicubic", align_corners=False
    )[0].clamp_(0.0, 1.0)

    mask_float = valid_mask.float()[None, None]
    weighted_depth = F.interpolate(
        (depth * valid_mask)[None, None],
        output_size,
        mode="bilinear",
        align_corners=False,
    )[0, 0]
    resized_weight = F.interpolate(
        mask_float, output_size, mode="bilinear", align_corners=False
    )[0, 0]
    resized_mask = F.interpolate(
        mask_float, output_size, mode="nearest"
    )[0, 0].bool()
    depth = weighted_depth / resized_weight.clamp_min(1e-6)
    depth = torch.where(resized_mask, depth, torch.zeros_like(depth))
    return image, depth, resized_mask


class UWD(Dataset):
    """Paired underwater RGB and dense Hypersim depth.

    The transform keeps aspect ratio, resizes the shorter required dimension,
    then uses a random crop for training and a center crop otherwise. All
    geometric operations are shared by RGB, depth, and validity mask.
    """

    def __init__(
        self,
        root: str | Path,
        manifest_path: str | Path,
        mode: str = "train",
        size: int | Sequence[int] = 518,
        random_flip: bool = True,
    ) -> None:
        if mode not in {"train", "val", "test"}:
            raise ValueError(f"unsupported mode: {mode}")

        self.root = Path(root)
        self.manifest_path = Path(manifest_path)
        self.mode = mode
        self.output_size = _parse_size(size)
        self.random_flip = random_flip
        self.samples = self._read_manifest(self.manifest_path)

        if not self.samples:
            raise ValueError(f"manifest contains no samples: {self.manifest_path}")

    @staticmethod
    def _read_manifest(path: Path) -> List[Dict[str, object]]:
        samples: List[Dict[str, object]] = []
        with path.open("r", encoding="utf-8") as handle:
            for line_number, line in enumerate(handle, start=1):
                line = line.strip()
                if not line:
                    continue
                sample = json.loads(line)
                required = {"rgb", "depth", "scene_id", "frame_id", "water_type"}
                missing = required.difference(sample)
                if missing:
                    raise ValueError(
                        f"{path}:{line_number} missing fields: {sorted(missing)}"
                    )
                samples.append(sample)
        return samples

    def __len__(self) -> int:
        return len(self.samples)

    def _transform(
        self,
        image: torch.Tensor,
        depth: torch.Tensor,
        valid_mask: torch.Tensor,
    ) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        target_h, target_w = self.output_size
        source_h, source_w = depth.shape
        scale = max(target_h / source_h, target_w / source_w)
        resized_h = max(target_h, round(source_h * scale))
        resized_w = max(target_w, round(source_w * scale))

        image, depth, valid_mask = _resize_dense_pair(
            image, depth, valid_mask, (resized_h, resized_w)
        )

        if self.mode == "train":
            top = random.randint(0, resized_h - target_h)
            left = random.randint(0, resized_w - target_w)
        else:
            top = (resized_h - target_h) // 2
            left = (resized_w - target_w) // 2

        image = image[:, top : top + target_h, left : left + target_w]
        depth = depth[top : top + target_h, left : left + target_w]
        valid_mask = valid_mask[top : top + target_h, left : left + target_w]

        if self.mode == "train" and self.random_flip and random.random() < 0.5:
            image = image.flip(-1)
            depth = depth.flip(-1)
            valid_mask = valid_mask.flip(-1)

        mean = image.new_tensor((0.485, 0.456, 0.406))[:, None, None]
        std = image.new_tensor((0.229, 0.224, 0.225))[:, None, None]
        image = (image - mean) / std
        return image, depth, valid_mask

    def __getitem__(self, index: int) -> Dict[str, object]:
        record = self.samples[index]
        rgb_path = self.root / str(record["rgb"])
        depth_path = self.root / str(record["depth"])

        with Image.open(rgb_path) as pil_image:
            image_array = np.asarray(pil_image.convert("RGB"), dtype=np.float32) / 255.0
        image = torch.from_numpy(image_array).permute(2, 0, 1).contiguous()

        with h5py.File(depth_path, "r") as handle:
            if "dataset" not in handle:
                raise KeyError(f"HDF5 depth has no 'dataset' key: {depth_path}")
            depth = torch.from_numpy(
                np.asarray(handle["dataset"], dtype=np.float32)
            )

        if tuple(depth.shape) != tuple(image.shape[-2:]):
            raise ValueError(
                f"RGB/depth shape mismatch for {rgb_path}: "
                f"{tuple(image.shape[-2:])} vs {tuple(depth.shape)}"
            )

        valid_mask = torch.isfinite(depth) & (depth > 0)
        depth = torch.where(valid_mask, depth, torch.zeros_like(depth))
        image, depth, valid_mask = self._transform(image, depth, valid_mask)

        water_type = str(record["water_type"])
        if water_type not in WATER_TYPE_TO_LABEL:
            raise ValueError(f"unknown water type: {water_type}")

        return {
            "image": image,
            "depth": depth,
            "valid_mask": valid_mask,
            "water_label": torch.tensor(WATER_TYPE_TO_LABEL[water_type]),
            "water_type": water_type,
            "scene_id": str(record["scene_id"]),
            "frame_id": str(record["frame_id"]),
            "image_path": str(rgb_path),
            "depth_path": str(depth_path),
        }
